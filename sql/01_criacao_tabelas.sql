-- Banco de dados para gestão/faturamento de uma clínica
-- Criação das tabelas

CREATE TABLE public.pacientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    data_nascimento DATE,
    ativo BOOLEAN DEFAULT TRUE
);

CREATE TABLE public.profissionais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    registro_profissional VARCHAR(30) UNIQUE,
    ativo BOOLEAN DEFAULT TRUE
);

CREATE TABLE public.atividades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT,
    ativo BOOLEAN DEFAULT TRUE
);

CREATE TABLE public.procedimentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    valor_particular NUMERIC(10,2),
    ativo BOOLEAN DEFAULT TRUE
);

CREATE TABLE public.convenios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    prazo_analise_dias INTEGER,
    ativo BOOLEAN DEFAULT TRUE,
    valor NUMERIC(10,2),
    tabela VARCHAR(50),
    valor_filme_m2 NUMERIC(10,2)
);

CREATE TABLE public.categoria_despesas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT,
    ativo BOOLEAN DEFAULT TRUE
);

CREATE TABLE public.profissional_atividades (
    profissional_id INTEGER NOT NULL,
    atividade_id INTEGER NOT NULL,
    PRIMARY KEY (profissional_id, atividade_id),
    FOREIGN KEY (profissional_id) REFERENCES public.profissionais(id),
    FOREIGN KEY (atividade_id) REFERENCES public.atividades(id)
);

CREATE TABLE public.atendimentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL,
    convenio_id INTEGER,
    data_atendimento DATE NOT NULL,
    status VARCHAR(30) DEFAULT 'Realizado',
    tipo_atendimento VARCHAR(30),
    FOREIGN KEY (paciente_id) REFERENCES public.pacientes(id),
    FOREIGN KEY (convenio_id) REFERENCES public.convenios(id)
);

CREATE TABLE public.atendimento_procedimentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id INTEGER NOT NULL,
    profissional_id INTEGER NOT NULL,
    procedimento_id INTEGER NOT NULL,
    valor_cobrado NUMERIC(10,2) NOT NULL,
    FOREIGN KEY (atendimento_id) REFERENCES public.atendimentos(id),
    FOREIGN KEY (profissional_id) REFERENCES public.profissionais(id),
    FOREIGN KEY (procedimento_id) REFERENCES public.procedimentos(id)
);

CREATE TABLE public.convenio_procedimentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    convenio_id INTEGER NOT NULL,
    procedimento_id INTEGER NOT NULL,
    especialidade VARCHAR(100) NOT NULL,
    tipo_guia VARCHAR(50),
    codigo VARCHAR(30),
    valor_convenio NUMERIC(10,2) NOT NULL,
    ativo BOOLEAN DEFAULT TRUE,
    categoria VARCHAR(50) NOT NULL DEFAULT 'Padrão',
    UNIQUE (convenio_id, procedimento_id, especialidade, categoria),
    FOREIGN KEY (convenio_id) REFERENCES public.convenios(id),
    FOREIGN KEY (procedimento_id) REFERENCES public.procedimentos(id)
);

CREATE TABLE public.faturamentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id INTEGER NOT NULL,
    numero_guia VARCHAR(30) NOT NULL UNIQUE,
    tipo_guia VARCHAR(30) NOT NULL,
    data_envio DATE,
    valor_enviado NUMERIC(10,2) NOT NULL,
    status VARCHAR(30) DEFAULT 'Pendente',
    data_retorno DATE,
    valor_glosado NUMERIC(10,2) DEFAULT 0,
    observacao TEXT,
    FOREIGN KEY (atendimento_id) REFERENCES public.atendimentos(id)
);

CREATE TABLE public.recebimentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faturamento_id INTEGER NOT NULL,
    data_recebimento DATE NOT NULL,
    valor_recebido NUMERIC(10,2) NOT NULL,
    forma_pagamento VARCHAR(50),
    observacao TEXT,
    FOREIGN KEY (faturamento_id) REFERENCES public.faturamentos(id)
);

CREATE TABLE public.despesas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id INTEGER NOT NULL,
    descricao VARCHAR(200) NOT NULL,
    data_despesa DATE NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    data_vencimento DATE,
    data_pagamento DATE,
    status VARCHAR(30) DEFAULT 'Pendente',
    FOREIGN KEY (categoria_id) REFERENCES public.categoria_despesas(id)
);


